"""Mechanical spelling translation of the fixed plant OpenCL variant to CUDA C++.
No equations, traversal order, physical parameters, or clipping rules are changed.
The generated file is checked in; source hashes make stale generation detectable.
"""
import pathlib,re,subprocess,json,hashlib
root=pathlib.Path(__file__).resolve().parents[1]; src=root/'Physics/PowderCore/src'
names=['granular_plant_cl.inc','granular_kernels.inc']
text='\n'.join(''.join(re.findall(r'R"CLC\((.*?)\)CLC"',(src/n).read_text(),re.S)) for n in names)
begin=text.index('__kernel void init_boundary_groups('); end=text.index('float3 boundary_eval(',begin)
text=text[:begin]+text[end:]
defs={'GRANULAR_PLANT':1,'GRANULAR_BOUNDS_FAST':1,'GRANULAR_KERNEL_OPTIMIZE':1,'PLANT_WALL_MODE':5,'PLANT_THREADED':1}
scratch=root/'Intermediate/CUDA/generated';scratch.mkdir(parents=True,exist_ok=True)
raw=scratch/'plant_preprocess.cpp';raw.write_text(text)
cl='C:/Program Files/Microsoft Visual Studio/2022/Community/VC/Tools/MSVC/14.44.35207/bin/Hostx64/x64/cl.exe'
r=subprocess.run([cl,'/nologo','/EP','/TP',*[f'/D{k}={v}' for k,v in defs.items()],str(raw)],capture_output=True,text=True,check=True)
text=r.stdout
text=re.sub(r'\((float[234]|int[234])\)\s*\(',r'\1(',text)
text=text.replace('__kernel void','extern "C" __global__ void').replace('__global ','')
# Reintroduce CUDA address-space marker after removing OpenCL pointer qualifiers.
text=text.replace('extern "C" void','extern "C" __global__ void')
text=re.sub(r'^(float[234]?|int[234]?|void) (\w+)\(',r'__device__ \1 \2(',text,flags=re.M)
text=re.sub(r'\.([xyzw]{2,3})\b',r'.\1()',text)
# OpenCL writable swizzles have explicit setters in our vector adapter.
text=text.replace('pos[i].xyz()+=v*dt;','pos[i].set_xyz(pos[i].xyz()+v*dt);')
text=text.replace('pos[i].xyz()=boundaries(p,r,angle,gate,&wn,&wv,bounds);','pos[i].set_xyz(boundaries(p,r,angle,gate,&wn,&wv,bounds));')
text=re.sub(r'\b(sqrt|sin|cos|pow|fabs|copysign|fmin|fmax|floor)\(',r'cl_\1(',text)
def kernel_span(source,name):
    start=source.index('extern "C" __global__ void '+name+'(')
    opening=source.index('{',start);depth=1;end=opening+1
    while depth:
        depth+=(source[end]=='{')-(source[end]=='}');end+=1
    return start,opening,end
for name in ['build_candidates','reuse_begin','reuse_check','audit_candidates','project_boundary','probe_boundary']:
    start,opening,end=kernel_span(text,name);text=text[:start]+text[end:]
for name in ['solve','velocity']:
    start,opening,end=kernel_span(text,name)
    signature=text[start:opening].replace(name+'(',name+'_graph(').replace('float angle','const float* angles,unsigned angle_index')
    text+='\n'+signature+'{float angle=angles[angle_index];'+text[opening+1:end]+'\n'
out=src/'cuda_plant_kernels.cuh'
out.write_text('// Generated by Scripts/cuda_generate_kernels.py. Do not edit equations here.\n'+text)
(root/'Docs/CUDA20261118/kernel_translation.json').write_text(json.dumps({'defines':defs,'input_sha256':{n:hashlib.sha256((src/n).read_bytes()).hexdigest() for n in names},'output_sha256':hashlib.sha256(out.read_bytes()).hexdigest()},indent=2))
print('Generated',out,len(text))
